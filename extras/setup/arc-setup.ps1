# Arc for Firefox: give Arc the whole window (Windows).
#
# Adds Arc's layout to the Firefox profile that has Arc installed:
#   <profile>\chrome\userChrome.css  hides Firefox's tab strip and toolbar
#   <profile>\user.js                turns the stylesheet on, horizontal tabs,
#                                    opens Arc at startup
#   <profile>\customKeys.json        clears Firefox's Ctrl+T and Ctrl+W so Arc
#                                    can handle them
# Your own CSS and prefs are kept: Arc only manages its marked block.
#
# Usage:  powershell -ExecutionPolicy Bypass -File arc-setup.ps1             set up (or update)
#         powershell -ExecutionPolicy Bypass -File arc-setup.ps1 -Uninstall  remove Arc's blocks
# Generated by scripts/build-setup.mjs; edit extras/ instead.
param([switch]$Uninstall)
$ErrorActionPreference = "Stop"

$AddonId = "arc@sidebar-pliha"
$CssBegin = "/* >>> Arc for Firefox >>> */"
$CssEnd = "/* <<< Arc for Firefox <<< */"
$JsBegin = "// >>> Arc for Firefox >>>"
$JsEnd = "// <<< Arc for Firefox <<<"

$root = Join-Path $env:APPDATA "Mozilla\Firefox\Profiles"
if (-not (Test-Path $root)) { Write-Error "No Firefox profiles found in $root" }

$all = @(Get-ChildItem $root -Directory | Where-Object { Test-Path (Join-Path $_.FullName "prefs.js") })
$arc = @($all | Where-Object {
  $ext = Join-Path $_.FullName "extensions.json"
  (Test-Path $ext) -and ((Get-Content $ext -Raw) -match [regex]::Escape('"id":"' + $AddonId + '"'))
})

if ($arc.Count -gt 0) { $candidates = $arc } else {
  Write-Host "No Firefox profile with Arc installed was found. Install Arc first, or pick a profile:"
  $candidates = $all
}
if ($candidates.Count -eq 0) { Write-Error "No Firefox profiles found." }

$target = $candidates[0]
if ($candidates.Count -gt 1) {
  Write-Host "Several Firefox profiles found:"
  for ($i = 0; $i -lt $candidates.Count; $i++) { Write-Host ("  {0}) {1}" -f ($i + 1), $candidates[$i].Name) }
  $pick = [int](Read-Host ("Which one? [1-{0}]" -f $candidates.Count))
  if ($pick -lt 1 -or $pick -gt $candidates.Count) { Write-Error "Out of range." }
  $target = $candidates[$pick - 1]
}

# Replace (or remove) the marked block in a file, keeping everything else.
function Write-Block($path, $begin, $end, $content) {
  New-Item -ItemType Directory -Force -Path (Split-Path $path) | Out-Null
  # A linked file belongs to something else; writing the block would edit that.
  if ((Test-Path $path) -and (Get-Item $path -Force).LinkType) {
    Write-Host "Skipping $path: it is a link, so it is managed elsewhere."
    return
  }
  $text = if (Test-Path $path) { [IO.File]::ReadAllText($path) } else { "" }
  $pattern = [regex]::Escape($begin) + "[\s\S]*?" + [regex]::Escape($end) + "\r?\n?"
  $text = [regex]::Replace($text, $pattern, "").TrimEnd()
  if (-not $Uninstall) {
    if ($text) { $text += "`n`n" }
    $text += "$begin`n$content`n$end`n"
  } elseif ($text) { $text += "`n" }
  [IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding $false))
}

