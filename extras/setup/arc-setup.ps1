$prefs = @'
// ArcFox: copy into your Firefox profile folder (next to prefs.js).
// Firefox applies these on every start.

// Load chrome/userChrome.css.
user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);
// Horizontal tabs (their strip is hidden; ArcFox lists the tabs).
user_pref("sidebar.verticalTabs", false);
// Native title bar: it holds the window buttons once the tab strip is hidden.
user_pref("browser.tabs.inTitlebar", 0);
// Closing the last tab keeps the window (with a new tab), like Arc.
user_pref("browser.tabs.closeWindowWithLastTab", false);
// A video pops out into Picture-in-Picture when you leave its tab, and goes back
// when you return, like Arc. Firefox has this built in; some profiles have it off.
user_pref("media.videocontrols.picture-in-picture.enabled", true);
user_pref("media.videocontrols.picture-in-picture.enable-when-switching-tabs.enabled", true);
// Reopen windows and tabs, including the open ArcFox sidebar.
user_pref("browser.startup.page", 3);
// Arc's panel state (open, and how wide) lives in sidebar.backupState, which
// Firefox writes itself. The setup seeds it once in prefs.js instead of here:
// a user_pref would be re-applied at every start, throwing away a width the
// sidebar had been dragged to.
'@

# Firefox's own Ctrl+T is a reserved shortcut, so Arc's command bar can only
# have it once the built-in key is cleared. An empty entry in customKeys.json
# means "cleared"; other entries there are left alone.
$keysPath = Join-Path $target.FullName "customKeys.json"
$keys = [ordered]@{}
if (Test-Path $keysPath) {
  $raw = (Get-Content $keysPath -Raw).Trim()
  if ($raw) { try { (ConvertFrom-Json $raw).PSObject.Properties | ForEach-Object { $keys[$_.Name] = $_.Value } } catch {} }
}
foreach ($key in @("key_newNavigatorTab", "key_close")) {
  if ($Uninstall) { $keys.Remove($key) }
  elseif (-not $keys.Contains($key)) { $keys[$key] = @{} }
}
[IO.File]::WriteAllText($keysPath, (ConvertTo-Json $keys -Compress -Depth 5), (New-Object Text.UTF8Encoding $false))

# An Arc stylesheet outside Arc's block is an older copy from a manual
# install: it keeps applying, and rules the new block doesn't restate win.
$cssPath = Join-Path $target.FullName "chrome\userChrome.css"
if ((Test-Path $cssPath)) {
  $existing = Get-Content $cssPath -Raw
  if ($existing -match "arcfox-sidebar-width" -and -not $existing.Contains($CssBegin)) {
    Write-Host "Note: chrome\userChrome.css already has an Arc stylesheet outside Arc's block."
    Write-Host "      Remove that older copy, or the two will fight."
  }
}

Write-Block $cssPath $CssBegin $CssEnd $css
Write-Block (Join-Path $target.FullName "user.js") $JsBegin $JsEnd $prefs

# Open Arc's panel on a profile that has never had it open. This goes into
# prefs.js, which Firefox owns from then on: it records the width the sidebar
# is dragged to, and a user_pref would overwrite that at every start.
# Injected verbatim into the setup scripts by scripts/build-setup.mjs.
$prefsPath = Join-Path $target.FullName "prefs.js"
if (-not $Uninstall -and (Test-Path $prefsPath) -and -not ((Get-Content $prefsPath -Raw) -match 'sidebar\.backupState')) {
  $seed = 'user_pref("sidebar.backupState", "{\"command\":\"arc_sidebar-pliha-sidebar-action\",\"panelOpen\":true,\"launcherVisible\":false,\"launcherExpanded\":false}");'
  Add-Content $prefsPath $seed
  Write-Host "Seeded sidebar.backupState so Arc's panel opens; Firefox keeps its width from now on."
}

if ($Uninstall) {
  Write-Host "Removed Arc's layout from $($target.Name). Restart Firefox."
} else {
  Write-Host "Arc's layout is set up in $($target.Name). Quit Firefox completely and open it again."
}
