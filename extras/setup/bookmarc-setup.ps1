# BookmArc: give BookmArc the whole window (Windows).
#
# Adds BookmArc's layout to the Firefox profile that has BookmArc installed:
#   <profile>\chrome\userChrome.css  hides Firefox's tab strip, rounds the page
#   <profile>\user.js                turns the stylesheet on, horizontal tabs,
#                                    opens BookmArc at startup
#   <profile>\customKeys.json        clears Firefox's Ctrl+T, Ctrl+W and Ctrl+L so
#                                    BookmArc can handle them
# Your own CSS and prefs are kept: BookmArc only manages its marked block.
#
# Usage:  powershell -ExecutionPolicy Bypass -File bookmarc-setup.ps1             set up (or update)
#         powershell -ExecutionPolicy Bypass -File bookmarc-setup.ps1 -Uninstall  remove BookmArc's blocks
# Generated by scripts/build-setup.mjs; edit extras/ instead.
param([switch]$Uninstall)
$ErrorActionPreference = "Stop"

$AddonId = "bookmarc@pliha"
$CssBegin = "/* >>> BookmArc >>> */"
$CssEnd = "/* <<< BookmArc <<< */"
$JsBegin = "// >>> BookmArc >>>"
$JsEnd = "// <<< BookmArc <<<"

$base = Join-Path $env:APPDATA "Mozilla\Firefox"
# Candidate profile folders: the ones profiles.ini lists (they can live
# anywhere), then the usual ones in Profiles.
$dirs = @()
$ini = Join-Path $base "profiles.ini"
if (Test-Path $ini) {
  $path = $null
  $rel = $true
  foreach ($line in @(Get-Content $ini) + "[end]") {
    if ($line -match '^\[') {
      if ($path) { $dirs += $(if ($rel) { Join-Path $base $path } else { $path }) }
      $path = $null
      $rel = $true
    } elseif ($line -match '^Path=(.+)$') { $path = $Matches[1] -replace '/', '\' }
    elseif ($line -match '^IsRelative=(\d)') { $rel = $Matches[1] -ne '0' }
  }
}
$profiles = Join-Path $base "Profiles"
if (Test-Path $profiles) { $dirs += @(Get-ChildItem $profiles -Directory | ForEach-Object { $_.FullName }) }

$all = @($dirs | Where-Object { Test-Path (Join-Path $_ "prefs.js") } | Sort-Object -Unique | ForEach-Object { Get-Item $_ })
$bookmarc = @($all | Where-Object {
  $ext = Join-Path $_.FullName "extensions.json"
  (Test-Path $ext) -and ((Get-Content $ext -Raw) -match [regex]::Escape('"id":"' + $AddonId + '"'))
})

if ($bookmarc.Count -gt 0) { $candidates = $bookmarc } else {
  Write-Host "No Firefox profile with BookmArc installed was found. Install BookmArc first, or pick a profile:"
  $candidates = $all
}
if ($candidates.Count -eq 0) { Write-Error "No Firefox profiles found." }

$target = $candidates[0]
if ($candidates.Count -gt 1) {
  Write-Host "Several Firefox profiles found:"
  for ($i = 0; $i -lt $candidates.Count; $i++) { Write-Host ("  {0}) {1}" -f ($i + 1), $candidates[$i].Name) }
  $pick = [int](Read-Host ("Which one? [1-{0}]" -f $candidates.Count))
  if ($pick -lt 1 -or $pick -gt $candidates.Count) { Write-Error "Out of range." }
  $target = $candidates[$pick - 1]
}

# Replace (or remove) the marked block in a file, keeping everything else.
function Write-Block($path, $begin, $end, $content) {
  New-Item -ItemType Directory -Force -Path (Split-Path $path) | Out-Null
  # A linked file belongs to something else; writing the block would edit that.
  if ((Test-Path $path) -and (Get-Item $path -Force).LinkType) {
    Write-Host "Skipping $path: it is a link, so it is managed elsewhere."
    return
  }
  $text = if (Test-Path $path) { [IO.File]::ReadAllText($path) } else { "" }
  $pattern = [regex]::Escape($begin) + "[\s\S]*?" + [regex]::Escape($end) + "\r?\n?"
  $text = [regex]::Replace($text, $pattern, "").TrimEnd()
  if (-not $Uninstall) {
    if ($text) { $text += "`n`n" }
    $text += "$begin`n$content`n$end`n"
  } elseif ($text) { $text += "`n" }
  [IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding $false))
}

$css = @'
/*
 * BookmArc layout for Firefox. Always on: the sidebar replaces the tab strip.
 * Firefox's toolbar (back/forward, address bar, extension buttons) stays on top,
 * and the window keeps its native title bar (browser.tabs.inTitlebar = 0 in
 * extras/user.js) for the window buttons.
 *
 * Setup (pair with extras/user.js, which also opens the sidebar at startup):
 *   1. about:support -> Profile Folder -> Open. Create a "chrome" folder there.
 *   2. Copy this file into it as chrome/userChrome.css.
 *   3. Copy extras/user.js into the profile folder, then restart Firefox.
 */

:root {
  /* Starting width only: drag the edge to resize, Firefox remembers it. */
  --bookmarc-sidebar-width: 260px;
  --bookmarc-sidebar-min: 180px;
  --bookmarc-sidebar-max: 620px;
}

/* ---------- The sidebar's background, for Firefox's own panels ---------- */

/* Firefox's panels (bookmarks, history, synced tabs) are chrome and can't read
   the sidebar's theme. While BookmArc colors Firefox (or another theme is on),
   they take the window frame's color, which is the sidebar's background.
   Otherwise they get the sidebar's default: #f3dddb, covering the whole
   background (shared/store.js); dark mode keeps Firefox's dark panels readable. */
:root {
  --bookmarc-panel-bg: #f3dddb;
}

@media (prefers-color-scheme: dark) {
  :root {
    --bookmarc-panel-bg: #1c1a22;
  }
}

:root[lwtheme] {
  --bookmarc-panel-bg: var(--lwt-accent-color, #f3dddb);
}

/* The panel area carries the color; Firefox's panels then let it through. */
#sidebar-box,
#sidebar {
  background-color: var(--bookmarc-panel-bg) !important;
}
:root {
  --sidebar-background-color: var(--bookmarc-panel-bg) !important;
}

@-moz-document url-prefix("chrome://browser/content/places/"),
  url-prefix("chrome://browser/content/syncedtabs/"),
  url-prefix("chrome://browser/content/genai/"),
  url-prefix("chrome://browser/content/sidebar/") {
  :root,
  body,
  #sidebar-panel-header,
  #history-panel,
  #bookmarksPanel,
  #syncedTabsContent,
  tree,
  tree > treechildren {
    background: transparent !important;
    background-color: transparent !important;
  }
}

/* ---------- Firefox chrome the sidebar replaces ---------- */

/* Firefox's sidebar launcher and the panel header ("BookmArc  x"):
   #sidebar-header in the old sidebar; #sidebar-panel-header in the new one,
   which lives inside the panel document (webext-panels.xhtml). */
#sidebar-container,
#sidebar-launcher-splitter,
#sidebar-header {
  visibility: collapse !important;
  display: none !important;
}

/* The sidebar's sidebar is resizable: Firefox's splitter stays, as an invisible grab
   strip on the edge (it draws the border the sidebar removed otherwise). Firefox
   remembers the width it's dragged to. */
#sidebar-splitter {
  /* No display override: a <splitter> drags because of its own frame, and
     forcing a CSS display (flex) replaces that frame — the strip then looks
     right but stops resizing once the page lays out. Visibility is stated
     because an older copy of this file collapses the splitter. */
  visibility: visible !important;
  appearance: none !important;
  width: 8px !important;
  min-width: 8px !important;
  /* Entirely over the sidebar: the half that used to hang into the content
     area sits above a remote page, which swallows the drag once it loads. */
  margin-inline-start: -8px !important;
  margin-inline-end: 0 !important;
  pointer-events: auto !important;
  border: 0 !important;
  background: transparent !important;
  cursor: col-resize !important;
  z-index: 11 !important;
}

/* Panel closed: no edge to drag, and the strip would otherwise sit over the
   page and swallow clicks. */
#sidebar-box[hidden] + #sidebar-splitter {
  display: none !important;
}

/* The panel header belongs to the panel's own document, and userChrome.css
   styles every chrome document — so hide it only in the sidebar's panel. Firefox's
   own panels (bookmarks, history, synced tabs, AI chat) keep their title
   and close button. */
@-moz-document url-prefix("chrome://browser/content/webext-panels.xhtml") {
  #sidebar-panel-header {
    visibility: collapse !important;
    display: none !important;
  }
}

/* Newer Firefox puts the panel header in the browser window, right above the
   panel: hide it while the sidebar shows the sidebar's panel. */
#sidebar-box:has(> .sidebar-browser-stack > #sidebar[src*="webext-panels"]) > #sidebar-panel-header {
  visibility: collapse !important;
  display: none !important;
}

/* The tab strip: the sidebar lists the tabs. The window buttons live in the native
   title bar (browser.tabs.inTitlebar = 0), so the whole strip can go. The sidebar's
   menu can bring it back ("Show Firefox Tab Bar"): BookmArc then starts each
   window's title with an invisible mark (U+200B, windows.update titlePreface). */
#main-window:not([titlepreface^="\200B"]) #TabsToolbar {
  visibility: collapse !important;
}

/* Sharp edge between the sidebar and the page: Firefox rounds and shadows both the
   sidebar panel and the content area. */
#sidebar,
#sidebar-box,
.sidebar-browser-stack,
#tabbrowser-tabbox,
#tabbrowser-tabpanels,
.browserSidebarContainer,
.browserContainer,
.browserStack,
#tabbrowser-tabpanels browser {
  border-radius: 0 !important;
  border: none !important;
  outline: none !important;
  box-shadow: none !important;
  margin: 0 !important;
}

/* The sidebar's page card: while the sidebar is open, the page gets a rounded top-left
   corner and a soft shadow falling onto the sidebar. The sidebar reaches 8px
   under the page (its own padding), so the rounded corner shows the sidebar's
   real color, custom theme colors included. */
#main-window:has(#sidebar-box:not([hidden])) #sidebar-box {
  margin-inline-end: -8px !important;
}
#main-window:has(#sidebar-box:not([hidden])) #tabbrowser-tabbox {
  position: relative !important;
  z-index: 1 !important;
  border-radius: 8px 0 0 0 !important;
  overflow: clip !important;
  box-shadow: 0 0 0 0.5px rgba(0, 0, 0, 0.14), 0 1px 8px rgba(0, 0, 0, 0.16) !important;
}

/* Firefox leaves a gap under the sidebar (padding-block-end); the sidebar fills it. */
#sidebar-box,
#sidebar-container,
.sidebar-browser-stack {
  padding: 0 !important;
}

/* The separator line itself (Firefox draws it as a border on the sidebar). */
:root {
  --sidebar-border-color: transparent !important;
  --chrome-content-separator-color: transparent !important;
}

/* Starting width and limits for the sidebar's panel. */
#sidebar-box {
  width: var(--bookmarc-sidebar-width);
  min-width: var(--bookmarc-sidebar-min) !important;
  max-width: var(--bookmarc-sidebar-max) !important;
}

/* ---------- Firefox's own sidebar panels ---------- */

/* When the sidebar shows one of Firefox's panels instead of the sidebar's (which
   Firefox loads as webext-panels.xhtml): same width as the sidebar's own panel (drag
   the edge to change both). Firefox asks for 400px for the AI chat; the sidebar's
   width wins. */
#main-window:has(#sidebar[src]:not([src*="webext-panels"]):not([src="about:blank"])) #sidebar-box {
  min-width: var(--bookmarc-sidebar-min) !important;
}

/* The add-on's own small windows are popups: no toolbar. */
#main-window[chromehidden~="toolbar"] #nav-bar {
  display: none !important;
}
'@

$prefs = @'
// BookmArc: copy into your Firefox profile folder (next to prefs.js).
// Firefox applies these on every start.

// Load chrome/userChrome.css.
user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);
// Horizontal tabs (their strip is hidden; the sidebar lists the tabs).
user_pref("sidebar.verticalTabs", false);
// Native title bar: it holds the window buttons once the tab strip is hidden.
user_pref("browser.tabs.inTitlebar", 0);
// Closing the last tab keeps the window (with a new tab).
user_pref("browser.tabs.closeWindowWithLastTab", false);
// A video pops out into Picture-in-Picture when you leave its tab, and goes back
// when you return. Firefox has this built in; some profiles have it off.
user_pref("media.videocontrols.picture-in-picture.enabled", true);
user_pref("media.videocontrols.picture-in-picture.enable-when-switching-tabs.enabled", true);
// Reopen windows and tabs, including the open sidebar.
user_pref("browser.startup.page", 3);
// the sidebar's panel state (open, and how wide) lives in sidebar.backupState, which
// Firefox writes itself. The setup seeds it once in prefs.js instead of here:
// a user_pref would be re-applied at every start, throwing away a width the
// sidebar had been dragged to.
'@

# Firefox's own Ctrl+T is a reserved shortcut, so BookmArc's command bar can only
# have it once the built-in key is cleared (likewise Ctrl+W, and Ctrl+L, which
# otherwise focuses the address bar). An empty entry in customKeys.json
# means "cleared"; other entries there are left alone.
$keysPath = Join-Path $target.FullName "customKeys.json"
$keys = [ordered]@{}
if (Test-Path $keysPath) {
  $raw = (Get-Content $keysPath -Raw).Trim()
  if ($raw) { try { (ConvertFrom-Json $raw).PSObject.Properties | ForEach-Object { $keys[$_.Name] = $_.Value } } catch {} }
}
foreach ($key in @("key_newNavigatorTab", "key_close", "focusURLBar")) {
  if ($Uninstall) { $keys.Remove($key) }
  elseif (-not $keys.Contains($key)) { $keys[$key] = @{} }
}
[IO.File]::WriteAllText($keysPath, (ConvertTo-Json $keys -Compress -Depth 5), (New-Object Text.UTF8Encoding $false))

# A BookmArc stylesheet outside BookmArc's block is an older copy from a manual
# install: it keeps applying, and rules the new block doesn't restate win.
$cssPath = Join-Path $target.FullName "chrome\userChrome.css"
if ((Test-Path $cssPath)) {
  $existing = Get-Content $cssPath -Raw
  if ($existing -match "bookmarc-sidebar-width" -and -not $existing.Contains($CssBegin)) {
    Write-Host "Note: chrome\userChrome.css already has a BookmArc stylesheet outside BookmArc's block."
    Write-Host "      Remove that older copy, or the two will fight."
  }
}

Write-Block $cssPath $CssBegin $CssEnd $css
Write-Block (Join-Path $target.FullName "user.js") $JsBegin $JsEnd $prefs

# Open BookmArc's panel on a profile that has never had it open. This goes into
# prefs.js, which Firefox owns from then on: it records the width the sidebar
# is dragged to, and a user_pref would overwrite that at every start.
# Injected verbatim into the setup scripts by scripts/build-setup.mjs.
$prefsPath = Join-Path $target.FullName "prefs.js"
if (-not $Uninstall -and (Test-Path $prefsPath) -and -not ((Get-Content $prefsPath -Raw) -match 'sidebar\.backupState')) {
  $seed = 'user_pref("sidebar.backupState", "{\"command\":\"bookmarc_pliha-sidebar-action\",\"panelOpen\":true,\"launcherVisible\":false,\"launcherExpanded\":false}");'
  Add-Content $prefsPath $seed
  Write-Host "Seeded sidebar.backupState so BookmArc's panel opens; Firefox keeps its width from now on."
}

if ($Uninstall) {
  Write-Host "Removed BookmArc's layout from $($target.Name). Restart Firefox."
} else {
  Write-Host "BookmArc's layout is set up in $($target.Name). Quit Firefox completely and open it again."
}
