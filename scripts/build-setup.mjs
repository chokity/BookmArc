// Builds the one-step layout setup scripts from extras/userChrome.css and
// extras/user.js, so they always ship the current files:
//   extras/setup/bookmarc-setup.txt  (macOS, Linux; downloaded as bookmarc-setup.sh)
//   extras/setup/bookmarc-setup.ps1  (Windows)
// Run: npm run build:setup
import fs from "node:fs";

const css = fs.readFileSync("extras/userChrome.css", "utf8").trimEnd();
const prefs = fs.readFileSync("extras/user.js", "utf8").trimEnd();
const keys = fs.readFileSync("extras/setup-keys.sh.txt", "utf8").trimEnd();
const seed = fs.readFileSync("extras/setup-seed.sh.txt", "utf8").trimEnd();
const seedPs = fs.readFileSync("extras/setup-seed.ps1.txt", "utf8").trimEnd();

for (const [name, text] of [["css", css], ["prefs", prefs]]) {
  if (text.includes("BOOKMARC_EOF") || /^'@/m.test(text)) throw new Error(`${name} contains a heredoc terminator`);
}

const sh = `#!/usr/bin/env bash
# BookmArc: give BookmArc the whole window (macOS & Linux).
#
# Adds BookmArc's layout to the Firefox profile that has BookmArc installed:
#   <profile>/chrome/userChrome.css  hides Firefox's tab strip, rounds the page
#   <profile>/user.js                turns the stylesheet on, horizontal tabs,
#                                    opens BookmArc at startup
#   <profile>/customKeys.json        clears Firefox's Cmd/Ctrl+T, Cmd/Ctrl+W and
#                                    Cmd/Ctrl+L so BookmArc can handle them
# Your own CSS and prefs are kept: BookmArc only manages its marked block.
#
# Usage:  bash bookmarc-setup.sh              set up (or update)
#         bash bookmarc-setup.sh --uninstall  remove BookmArc's blocks again
# Generated by scripts/build-setup.mjs; edit extras/ instead.
set -euo pipefail

ADDON_ID="bookmarc@pliha"
CSS_BEGIN="/* >>> BookmArc >>> */"
CSS_END="/* <<< BookmArc <<< */"
JS_BEGIN="// >>> BookmArc >>>"
JS_END="// <<< BookmArc <<<"

UNINSTALL=0
[ "\${1:-}" = "--uninstall" ] && UNINSTALL=1

case "$(uname -s)" in
  Darwin) BASES=("$HOME/Library/Application Support/Firefox") ;;
  *) BASES=("$HOME/.config/mozilla/firefox" "$HOME/.mozilla/firefox" "$HOME/snap/firefox/common/.mozilla/firefox" "$HOME/.var/app/org.mozilla.firefox/.mozilla/firefox") ;;
esac

# Candidate profile folders under a Firefox base folder: the ones profiles.ini
# lists (they can live anywhere), then the usual ones next to it.
profile_dirs() {
  local base="$1" dir
  if [ -f "$base/profiles.ini" ]; then
    tr -d '\\r' 2> /dev/null < "$base/profiles.ini" | awk -F= -v base="$base" '
      function emit() { if (path != "") print (rel == "0" ? path : base "/" path) }
      /^\\[/ { emit(); path = ""; rel = "1" }
      $1 == "Path" { path = substr($0, 6) }
      $1 == "IsRelative" { rel = $2 }
      END { emit() }'
  fi
  for dir in "$base"/Profiles/*/ "$base"/*/; do echo "\${dir%/}"; done
}

# Every Firefox profile folder (has prefs.js); BookmArc's first.
BOOKMARC=()
OTHER=()
SEEN="|"
while IFS= read -r dir; do
  [ -f "$dir/prefs.js" ] || continue
  case "$SEEN" in *"|$dir|"*) continue ;; esac
  SEEN="$SEEN$dir|"
  if grep -q "\\"id\\":\\"$ADDON_ID\\"" "$dir/extensions.json" 2>/dev/null; then BOOKMARC+=("$dir"); else OTHER+=("$dir"); fi
done < <(for base in "\${BASES[@]}"; do if [ -d "$base" ]; then profile_dirs "$base"; fi; done)

if [ \${#BOOKMARC[@]} -gt 0 ]; then
  CANDIDATES=("\${BOOKMARC[@]}")
else
  echo "No Firefox profile with BookmArc installed was found. Install BookmArc first, or pick a profile:"
  CANDIDATES=(\${OTHER[@]+"\${OTHER[@]}"})
fi
if [ \${#CANDIDATES[@]} -eq 0 ]; then
  echo "No Firefox profiles found." >&2
  # macOS privacy protection keeps the terminal out of other apps' data.
  for base in "\${BASES[@]}"; do
    [ -d "$base" ] || continue
    if ! ls "$base" > /dev/null 2>&1 || { [ -f "$base/profiles.ini" ] && ! cat "$base/profiles.ini" > /dev/null 2>&1; }; then
      echo "The system won't let this terminal read $base." >&2
      [ "$(uname -s)" = Darwin ] && echo "Allow it in System Settings > Privacy & Security > Full Disk Access (turn on your terminal app), then open a new terminal window and run this again." >&2
      break
    fi
  done
  exit 1
fi

PROFILE="\${CANDIDATES[0]}"
if [ \${#CANDIDATES[@]} -gt 1 ]; then
  echo "Several Firefox profiles found:"
  i=1
  for p in "\${CANDIDATES[@]}"; do echo "  $i) $(basename "$p")"; i=$((i + 1)); done
  printf "Which one? [1-%s] " "\${#CANDIDATES[@]}"
  read -r pick < /dev/tty
  case "$pick" in ''|*[!0-9]*) echo "Not a number." >&2; exit 1 ;; esac
  [ "$pick" -ge 1 ] && [ "$pick" -le \${#CANDIDATES[@]} ] || { echo "Out of range." >&2; exit 1; }
  PROFILE="\${CANDIDATES[$((pick - 1))]}"
fi

# Replace (or remove) the marked block in a file, keeping everything else.
write_block() {
  local file="$1" begin="$2" end="$3" content="$4" tmp
  mkdir -p "$(dirname "$file")"
  # A symlinked file belongs to something else (a dotfiles repo, or BookmArc's own
  # source in a development profile): writing the block would edit that.
  if [ -L "$file" ]; then
    echo "Skipping $file: it is a symlink, so it is managed elsewhere."
    return 0
  fi
  touch "$file"
  tmp="$(mktemp)"
  # Drop the old block (and trailing blank lines), keep everything else.
  awk -v b="$begin" -v e="$end" '
    index($0, b) { skip = 1 }
    !skip { if ($0 == "") blank++; else { while (blank > 0) { print ""; blank-- } print } }
    index($0, e) { skip = 0 }' "$file" > "$tmp"
  if [ "$UNINSTALL" -eq 0 ]; then
    [ -s "$tmp" ] && printf '\\n' >> "$tmp"
    printf '%s\\n%s\\n%s\\n' "$begin" "$content" "$end" >> "$tmp"
  fi
  cat "$tmp" > "$file"
  rm -f "$tmp"
}

# read -d '' (not $(cat <<...)): macOS bash 3.2 misparses quotes inside $( heredoc ).
IFS= read -r -d '' CSS <<'BOOKMARC_EOF' || true
${css}
BOOKMARC_EOF
CSS="\${CSS%$'\\n'}"

IFS= read -r -d '' PREFS <<'BOOKMARC_EOF' || true
${prefs}
BOOKMARC_EOF
PREFS="\${PREFS%$'\\n'}"

${keys}

# A BookmArc stylesheet outside BookmArc's block is an older copy from a manual
# install: it keeps applying, and rules the new block doesn't restate win.
if grep -q "bookmarc-sidebar-width" "$PROFILE/chrome/userChrome.css" 2>/dev/null &&
   ! grep -q "$CSS_BEGIN" "$PROFILE/chrome/userChrome.css" 2>/dev/null; then
  echo "Note: chrome/userChrome.css already has a BookmArc stylesheet outside BookmArc's block."
  echo "      Remove that older copy, or the two will fight."
fi

write_block "$PROFILE/chrome/userChrome.css" "$CSS_BEGIN" "$CSS_END" "$CSS"
write_block "$PROFILE/user.js" "$JS_BEGIN" "$JS_END" "$PREFS"

${seed}

if [ "$UNINSTALL" -eq 1 ]; then
  echo "Removed BookmArc's layout from $(basename "$PROFILE")."
  echo "Restart Firefox. user.js prefs already applied stay until you change them in about:config."
else
  echo "BookmArc's layout is set up in $(basename "$PROFILE")."
  echo "Quit Firefox completely and open it again."
fi
`;

const ps1 = `# BookmArc: give BookmArc the whole window (Windows).
#
# Adds BookmArc's layout to the Firefox profile that has BookmArc installed:
#   <profile>\\chrome\\userChrome.css  hides Firefox's tab strip, rounds the page
#   <profile>\\user.js                turns the stylesheet on, horizontal tabs,
#                                    opens BookmArc at startup
#   <profile>\\customKeys.json        clears Firefox's Ctrl+T, Ctrl+W and Ctrl+L so
#                                    BookmArc can handle them
# Your own CSS and prefs are kept: BookmArc only manages its marked block.
#
# Usage:  powershell -ExecutionPolicy Bypass -File bookmarc-setup.ps1             set up (or update)
#         powershell -ExecutionPolicy Bypass -File bookmarc-setup.ps1 -Uninstall  remove BookmArc's blocks
# Generated by scripts/build-setup.mjs; edit extras/ instead.
param([switch]$Uninstall)
$ErrorActionPreference = "Stop"

$AddonId = "bookmarc@pliha"
$CssBegin = "/* >>> BookmArc >>> */"
$CssEnd = "/* <<< BookmArc <<< */"
$JsBegin = "// >>> BookmArc >>>"
$JsEnd = "// <<< BookmArc <<<"

$base = Join-Path $env:APPDATA "Mozilla\\Firefox"
# Candidate profile folders: the ones profiles.ini lists (they can live
# anywhere), then the usual ones in Profiles.
$dirs = @()
$ini = Join-Path $base "profiles.ini"
if (Test-Path $ini) {
  $path = $null
  $rel = $true
  foreach ($line in @(Get-Content $ini) + "[end]") {
    if ($line -match '^\\[') {
      if ($path) { $dirs += $(if ($rel) { Join-Path $base $path } else { $path }) }
      $path = $null
      $rel = $true
    } elseif ($line -match '^Path=(.+)$') { $path = $Matches[1] -replace '/', '\\' }
    elseif ($line -match '^IsRelative=(\\d)') { $rel = $Matches[1] -ne '0' }
  }
}
$profiles = Join-Path $base "Profiles"
if (Test-Path $profiles) { $dirs += @(Get-ChildItem $profiles -Directory | ForEach-Object { $_.FullName }) }

$all = @($dirs | Where-Object { Test-Path (Join-Path $_ "prefs.js") } | Sort-Object -Unique | ForEach-Object { Get-Item $_ })
$bookmarc = @($all | Where-Object {
  $ext = Join-Path $_.FullName "extensions.json"
  (Test-Path $ext) -and ((Get-Content $ext -Raw) -match [regex]::Escape('"id":"' + $AddonId + '"'))
})

if ($bookmarc.Count -gt 0) { $candidates = $bookmarc } else {
  Write-Host "No Firefox profile with BookmArc installed was found. Install BookmArc first, or pick a profile:"
  $candidates = $all
}
if ($candidates.Count -eq 0) { Write-Error "No Firefox profiles found." }

$target = $candidates[0]
if ($candidates.Count -gt 1) {
  Write-Host "Several Firefox profiles found:"
  for ($i = 0; $i -lt $candidates.Count; $i++) { Write-Host ("  {0}) {1}" -f ($i + 1), $candidates[$i].Name) }
  $pick = [int](Read-Host ("Which one? [1-{0}]" -f $candidates.Count))
  if ($pick -lt 1 -or $pick -gt $candidates.Count) { Write-Error "Out of range." }
  $target = $candidates[$pick - 1]
}

# Replace (or remove) the marked block in a file, keeping everything else.
function Write-Block($path, $begin, $end, $content) {
  New-Item -ItemType Directory -Force -Path (Split-Path $path) | Out-Null
  # A linked file belongs to something else; writing the block would edit that.
  if ((Test-Path $path) -and (Get-Item $path -Force).LinkType) {
    Write-Host "Skipping $path: it is a link, so it is managed elsewhere."
    return
  }
  $text = if (Test-Path $path) { [IO.File]::ReadAllText($path) } else { "" }
  $pattern = [regex]::Escape($begin) + "[\\s\\S]*?" + [regex]::Escape($end) + "\\r?\\n?"
  $text = [regex]::Replace($text, $pattern, "").TrimEnd()
  if (-not $Uninstall) {
    if ($text) { $text += "\`n\`n" }
    $text += "$begin\`n$content\`n$end\`n"
  } elseif ($text) { $text += "\`n" }
  [IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding $false))
}

$css = @'
${css}
'@

$prefs = @'
${prefs}
'@

# Firefox's own Ctrl+T is a reserved shortcut, so BookmArc's command bar can only
# have it once the built-in key is cleared (likewise Ctrl+W, and Ctrl+L, which
# otherwise focuses the address bar). An empty entry in customKeys.json
# means "cleared"; other entries there are left alone.
$keysPath = Join-Path $target.FullName "customKeys.json"
$keys = [ordered]@{}
if (Test-Path $keysPath) {
  $raw = (Get-Content $keysPath -Raw).Trim()
  if ($raw) { try { (ConvertFrom-Json $raw).PSObject.Properties | ForEach-Object { $keys[$_.Name] = $_.Value } } catch {} }
}
foreach ($key in @("key_newNavigatorTab", "key_close", "focusURLBar")) {
  if ($Uninstall) { $keys.Remove($key) }
  elseif (-not $keys.Contains($key)) { $keys[$key] = @{} }
}
[IO.File]::WriteAllText($keysPath, (ConvertTo-Json $keys -Compress -Depth 5), (New-Object Text.UTF8Encoding $false))

# A BookmArc stylesheet outside BookmArc's block is an older copy from a manual
# install: it keeps applying, and rules the new block doesn't restate win.
$cssPath = Join-Path $target.FullName "chrome\\userChrome.css"
if ((Test-Path $cssPath)) {
  $existing = Get-Content $cssPath -Raw
  if ($existing -match "bookmarc-sidebar-width" -and -not $existing.Contains($CssBegin)) {
    Write-Host "Note: chrome\\userChrome.css already has a BookmArc stylesheet outside BookmArc's block."
    Write-Host "      Remove that older copy, or the two will fight."
  }
}

Write-Block $cssPath $CssBegin $CssEnd $css
Write-Block (Join-Path $target.FullName "user.js") $JsBegin $JsEnd $prefs

${seedPs}

if ($Uninstall) {
  Write-Host "Removed BookmArc's layout from $($target.Name). Restart Firefox."
} else {
  Write-Host "BookmArc's layout is set up in $($target.Name). Quit Firefox completely and open it again."
}
`;

fs.mkdirSync("extras/setup", { recursive: true });
// Plain .txt inside the add-on: add-on review flags any ".sh" in a file name.
// The download is named bookmarc-setup.sh.
fs.writeFileSync("extras/setup/bookmarc-setup.txt", sh);
fs.writeFileSync("extras/setup/bookmarc-setup.ps1", ps1.replace(/\n/g, "\r\n"));
console.log("wrote extras/setup/bookmarc-setup.txt and extras/setup/bookmarc-setup.ps1");
